export function getPlayingCardTheme(
  style: PaperSkyVisualStyle,
  dreamSightActive = false,
): PlayingCardTheme {
  if (dreamSightActive) return DREAM_SIGHT_THEME;
  return THEMES[style] ?? THEMES.pixel;
}

export function isRedSuit(suit: PlayingCardSuit): boolean {
  return suit === '♥' || suit === '♦';
}
